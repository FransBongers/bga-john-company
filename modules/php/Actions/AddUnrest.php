  public function stAddUnrest()
  {
    $args = $this->ctx->getArgs();
    $playerId = $args['playerId'];
    $regionId = $args['regionId'];
    $amount = $args['amount'];

    Regions::get($regionId)->addUnrest(Players::get($playerId), $amount);

    $this->resolveAction(['automatic' => true]);
  }

