  // .##.....##.##..........##.....##..##.....##.##.##.##
  // .#########.##..........##.....##..##.....##.##..####
  // .##.....##.##....##....##.....##..##.....##.##...###
  // .##.....##..######.....##....####..#######..##....##

  public function stPlaceUnrestInRegion()
  {
    $args = $this->ctx->getArgs();
    $playerId = $args['playerId'];
    $regionId = $args['regionId'];
    Regions::get($regionId)->addUnrest(Players::get($playerId), 1);

    $this->resolveAction(['automatic' => true, 'regionId' => $regionId], true);
  }

