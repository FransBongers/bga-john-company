  public function stParliamentMeetsResolveLaw()
  {
    $args = $this->ctx->getArgs();

    $passed = $args['passed'];
    $lawCardId = $args['lawCardId'];

    $law = LawCards::get($lawCardId);
    $law->resolveImmediateEffects($passed);

    $this->resolveAction(['automatic' => true]);
  }

